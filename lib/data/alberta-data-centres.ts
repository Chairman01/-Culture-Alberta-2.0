// ---------------------------------------------------------------------------
// Derived totals
// ---------------------------------------------------------------------------
export function isActive(dc: DataCentre): boolean {
  return dc.status !== 'operating' && dc.status !== 'inactive'
}

export function totals(list: DataCentre[] = DATA_CENTRES) {
  const active = list.filter(isActive)
  const proposedMW = active.reduce((sum, dc) => sum + (dc.demandMW ?? 0), 0)
  const operating = list.filter(dc => dc.status === 'operating')
  const operatingMW = operating.reduce((sum, dc) => sum + (dc.demandMW ?? 0), 0)
  return {
    total: list.length,
    active: active.length,
    operating: operating.length,
    underConstruction: list.filter(dc => dc.status === 'under-construction').length,
    proposedMW,
    operatingMW,
    municipalities: new Set(list.map(dc => dc.municipality)).size,
  }
}
