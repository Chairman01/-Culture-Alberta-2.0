export type DcStatus = 'proposed' | 'approved' | 'under-construction' | 'operating' | 'inactive'
export type DcPower = 'grid' | 'onsite-gas' | 'grid+onsite' | 'other' | 'undisclosed'
export type DcWorkload = 'ai' | 'crypto' | 'colocation' | 'mixed' | 'undisclosed'
export type DcRegion =
  | 'Edmonton Region'
  | 'Calgary Region'
  | 'Central Alberta'
  | 'Southern Alberta'
  | 'Northwest Alberta'
  | 'Northeast Alberta'

export interface DcSource {
  label: string
  url: string
}

export interface DataCentre {
  id: string
  name: string
  operator: string
  municipality: string
  region: DcRegion
  lat: number
  lng: number
  status: DcStatus
  /** Data centre electrical demand in MW at full build, when published. */
  demandMW: number | null
  demandNote?: string
  power: DcPower
  powerNote: string
  workload: DcWorkload
  /** Capital cost in CAD millions, when published. */
  costM: number | null
  jobsConstruction: number | null
  jobsPermanent: number | null
  timeline: string
  water?: string
  summary: string
  sources: DcSource[]
  /** ID in the Government of Alberta Major Projects Inventory, when listed there. */
  majorProjectId?: number
}

// Primary = a regulator, government or municipal record backs the entry.
// Reported = the best we have is the proponent's own material or press coverage.
const PRIMARY_HOSTS = ['aeso.ca', 'alberta.ca', 'auc.ab.ca', 'canada.ca', 'county', 'sturgeoncounty', 'wheatlandcounty', 'rockyview', 'rdcounty', 'stettler', 'lacombecounty', 'yhcounty', 'northernsunrise', 'vulcancounty', 'newell', 'olds.ca', 'strathmore.ca']
export type DcSourceTier = 'primary' | 'reported'
export function sourceTier(dc: DataCentre): DcSourceTier {
  if (dc.majorProjectId) return 'primary'
  return dc.sources.some(s => PRIMARY_HOSTS.some(h => s.url.includes(h))) ? 'primary' : 'reported'
}

